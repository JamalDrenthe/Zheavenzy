function generateDeterministicWaveform(seedStr: string): number[] {
  let hash = 0;
  for (let i = 0; i < seedStr.length; i++) {
    hash = (hash << 5) - hash + seedStr.charCodeAt(i);
    hash |= 0;
  }
  const seed = Math.abs(hash);
  const bars: number[] = [];
  for (let i = 0; i < 48; i++) {
    const p = i / 48;
    const wave1 = Math.sin(p * Math.PI * 3 + seed) * 0.3;
    const wave2 = Math.cos(p * Math.PI * 6 + (seed % 19)) * 0.2;
    const rnd = ((seed * (i + 17) * 9301 + 49297) % 233280) / 233280;
    const beat = (rnd - 0.5) * 0.3;
    const height = Math.max(0.18, Math.min(0.95, 0.5 + wave1 + wave2 + beat));
    bars.push(parseFloat(height.toFixed(2)));
  }
  return bars;
}

